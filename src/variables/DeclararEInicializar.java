package variables;

public class DeclararEInicializar {
	public static void main (String[] args) {
		// Declaración: se reserva el espacio, todavía sin valor
		int edad;
		// Inicialización: primer valor
		edad = 18;        
		
		 // Declaración + inicialización (lo más habitual)
		int curso = 1;    

		// Asignación: el 18 se sustituye y se pierde
		edad = 19;          

		// Varias del mismo tipo en una línea (sin abusar)
		int x = 0, y = 0;   

	}

}
